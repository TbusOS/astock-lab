def _old_score(a: dict, L: list) -> None:
    """对照:旧的三维打分说什么。**只是对照,不是结论。**

    为什么还留着它:三维回答的是另外三个问题(相对自己历史贵不贵、
    份额在得还是在丢、推法有没有旁证),那三件事仍然值得单独看一眼。
    两边给出相反的结论时,去看是哪一维和 EV 打架 —— 那通常比两个结论本身有用。
    """
    L.append("### 11.9 对照:旧的三维打分说什么")
    L.append("")
    L.append("这张表**不是这份报告的结论** —— 结论在上面,由期望值定。"
             "留着它是因为它回答的是另外三个问题,而那三件事值得单独看一眼。")
    L.append("")
    L.append("| 维度 | 分 | 依据 |")
    L.append("|---|---:|---|")
    for k in ("估值", "基本面", "确定性"):
        sc_, w = a[k]
        if k == "估值" and a.get("估值维失效"):
            w = (f"⚠ **这一维在「{a.get('行业')}」这个行业上本身就失效** —— "
                 f"周期 / 设备股的 PE 分位在盈利低谷给「便宜」的假信号、"
                 f"在高峰给「贵」的假信号。这个分数只当背景。原依据:{w}")
        L.append(f"| {k} | **{sc_:+d}** | {w} |")
    L.append(f"| **合计** | **{a['总分']:+d}** | 旧档位会给出「**{a['旧动作']}**」"
             f"(≥3 买入 · 1~2 持有 · 0 持有不加仓 · −1~−2 减仓 · ≤−3 清仓) |")
    L.append("")
    same = a["旧动作"].startswith(a["动作"][:2]) or a["动作"].startswith(a["旧动作"][:2])
    if same:
        L.append(f"**两边一致**:期望值给的是「{a['动作']}」,三维给的是"
                 f"「{a['旧动作']}」。一致不代表更对 —— "
                 f"它们共用了同一批数据,只是加总方式不同。")
    else:
        L.append(f"**两边不一致**:期望值给「{a['动作']}」,三维给「{a['旧动作']}」。"
                 f"**这本身是信息** —— 去看是哪一维和期望值打架:"
                 f"三维把「贵不贵」和「份额」当成同等重量的两票,"
                 f"期望值则把它们都折算成价位再按概率加权,"
                 f"所以**当某一维很极端时,两边会分叉**。以期望值为准,"
                 f"因为它能被季报证伪,而三维总分不能。")
    L.append("")
    if a.get("估值踩线"):
        L.append(f"- **估值这一维踩在档线上** {a['估值踩线']}。"
                 f"报告里按两位小数印,**看不出它离档线只有这么点距离**。")
    if a.get("边界判定数"):
        L.append(f"- **有 {a['边界判定数']} 个方法的适用性判定踩在阈值边上**"
                 f"(离阈值不到它的 10%)。阈值两边是两个相反的结论,而差距只有几个点 —— "
                 f"下季度重跑时这一维很可能整个翻面。翻面的时候先问"
                 f"「公司变了没有」,多半答案是没变,只是噪声过了线。")
    if not a.get("方法一致", True):
        L.append("- **这只票的几个方法区间不重叠**:它们都通过了自检,却互相矛盾。"
                 "至少有一个方法在它身上是错的,而我们不知道是哪一个。")
    L.append("")
