# 买入档「不追高」的上限:谨慎档目标价往上这么多百分比,超过就不追。
# **写死是故意的** —— 每只现想一个百分比等于没有规则,五只必须同一把尺。
# 为什么是 15:谨慎档是「净利下沿 × 倍数下沿」,两个偏空条件叠出来的**边界**,
# 不是预期;从它往上 15% 还在「谨慎档 → 中枢档」这段的下半截。
# 再往上,买入的理由就从「有安全边际」变成「赌中枢或乐观档兑现」——
# 那时候该做的是等,不是买。
ADD_CAP_PCT = 15

VAL_CUTS = (0.8, 1.2, 1.8, 2.5)      # 估值档线
VAL_EDGE = 0.02                       # 离档线多近算踩线


def val_edge_note(rel: float | None) -> str | None:
    """rel 离最近那条档线有多近。近到 0.02 以内就标出来。**只加文案,不动档线。**

    为什么要标:1.1949 和 1.2010 落在两个不同的档(「合理 +1」和「偏贵 0」),
    可它们只差 0.006 —— 而报告里按两位小数印,**两个都印成 1.20x**。
    读者看到的是同一个数字拿到了不同的分,却没有任何东西告诉他这是踩线。
    胜宏 2026-09-02 实测就是 1.1949,差 0.005 就换一档。

    和三个预测方法的边界标注同一条思路:阈值保持硬的(五只同一把尺、
    可以被质疑),但「这次踩在线上」必须如实说出来。
    """
    if rel is None:
        return None
    cut = min(VAL_CUTS, key=lambda c: abs(rel - c))
    gap = abs(rel - cut)
    if gap > VAL_EDGE:
        return None
    return (f"(精确值 **{rel:.3f}**,离 {cut:g} 这条档线只差 {gap:.3f} —— "
            f"**边界值,下季度可能翻档**)")


def score_valuation(rel: float | None):
    """rel = 现价 3+1 PE ÷ 自己历史 3+1 PE 的 p50。"""
    if rel is None:
        return 0, "算不出自己的历史 3+1 PE 带,估值这一维给 0 分"
    edge = val_edge_note(rel) or ""
    if rel < 0.8:
        return 2, f"现价只有自己历史中位的 {rel:.2f} 倍 —— **便宜**{edge}"
    if rel < 1.2:
        return 1, f"现价是自己历史中位的 {rel:.2f} 倍 —— **合理**{edge}"
    if rel < 1.8:
        return 0, f"现价是自己历史中位的 {rel:.2f} 倍 —— **偏贵**{edge}"
    if rel < 2.5:
        return -1, f"现价是自己历史中位的 {rel:.2f} 倍 —— **贵**{edge}"
    return -2, f"现价是自己历史中位的 {rel:.2f} 倍 —— **很贵**{edge}"


def score_chain(cp: dict | None, up_note: str = ""):
    """算不出来时给 0 分,**理由要照抄第 4 节的具体原因**。

    以前这里写死一句「没有对应的上游数据源」。2026-09-02 之后这句话会说谎:
    杰瑞的上游数据是有的(三桶油三大表都在),卡住的是可比季度只有 3 个。
    第 4 节说「数据也拿到了」,打分表说「没有数据源」—— 两处对不上,
    读者只能挑一个信。所以理由从同一个来源取,不各写各的。
    """
    if not cp:
        return 0, ("算不出相对上游的增速倍数,这一维给 0 分。"
                   + (up_note or "没有对应的上游数据源。"))
    # ⚠ 算得出来 ≠ 能拿来打分。四个可比点隔着好几个季度时,首尾一比照样得出
    #   一个像模像样的「优势在收窄」,而中间发生过什么完全看不见。
    #   表照样展示(让人看见数据长什么样),但不给分 —— 展示和证据是两件事。
    if not cp.get("可打分", True):
        return 0, (f"可比点 {'/'.join(cp.get('四点', []))} 不连续,"
                   f"横跨 {cp.get('跨越季度数', '?')} 个季度(连续的话应该是 4 个),"
                   f"看不出趋势,**只展示不打分**,这一维给 0 分")
    lv, tr = cp["终点"], cp["趋势"]
    if lv > 1.15 and tr == "优势在扩大":
        return 2, f"增速是上游开支的 {lv:.2f} 倍且**还在扩大** —— 在抢份额,而且越抢越快"
    if lv > 1.15:
        return 1, f"增速是上游开支的 {lv:.2f} 倍 —— 在得份额,但{tr}"
    if lv >= 0.85:
        return 0, f"增速倍数 {lv:.2f} —— 和上游基本同步,没有超额,{tr}"
    if tr == "优势在收窄":
        return -2, f"增速只有上游开支的 {lv:.2f} 倍且**还在往下** —— 行业在扩它没跟上"
    return -1, f"增速只有上游开支的 {lv:.2f} 倍 —— 慢于行业"


def score_confidence(n: int, consistent: bool, edge_n: int = 0):
    """确定性 = 几个方法适用,**再看它们同不同意**。

    n≥2 但区间不重叠时给 0 分,不给 +1:三个方法各说各话不是三重印证,
    是「至少有一个方法在这只票上是错的,而我们不知道是哪一个」。
    这比只有一个方法更该警惕 —— 一个方法至少还知道自己没有旁证。

    ⚠ **这里不再因为「没有上游数据源」额外降档。** 缺数据源是我们自己的
    工作缺口(没去抓,或者还没想清楚这只票的客户是谁),不是这只票该卖的理由。
    它已经在基本面那一维给 0 分了,再罚一次等于同一件事扣两遍。

    edge_n 只影响理由文字,不影响分数 —— 阈值是硬的,踩线也算数,
    但读者有权知道这个「3 个方法适用」是不是踩在线上得来的。
    """
    if n >= 2 and not consistent:
        why = (f"{n} 个方法都通过了自检,但区间不重叠、互相矛盾 —— "
               f"**这不构成互相印证**,至少有一个方法在这只票上是错的")
        base = 0
    else:
        base = {3: 1, 2: 0, 1: -1, 0: -2}.get(n, 0)
        why = f"三个预测方法里 {n} 个适用"
        if n >= 2:
            why += ",区间重叠、互相印证"
    if edge_n:
        why += f"(其中 {edge_n} 个判定在阈值边上,下季度可能翻面)"
    return base, why


# ── 打分 → 动作 ───────────────────────────────────────────────────────
ACTIONS = [
    (3, "买入 / 加仓", "长期(1 年以上,跨多个季报)",
     "基本面在变好而且估值不贵,这种组合不常见"),
    (1, "持有", "长期(1 年以上)", "值得拿着,但现在不是加仓的价位"),
    (0, "持有,但不加仓", "中期(2~4 个季度)",
     "没有明显的错,也没有明显的超额 —— 拿着看下个季报"),
    (-2, "减仓", "短期执行(1 个月内),保留底仓",
     "估值或基本面有一条明确变差,先把仓位降下来"),
    (-99, "清仓", "短期执行(1 个月内)",
     "估值和基本面同时不利,没有继续持有的理由"),
]


def decide(total: int):
    """旧的三维档位。**保留是为了对照**,不再决定动作。"""
    for cut, act, horizon, why in ACTIONS:
        if total >= cut:
            return act, horizon, why
    return ACTIONS[-1][1:]


def build(v: dict, f: dict, position: dict) -> dict:
    """三维打分(对照)+ 决策层(定动作)。**返回的键名全部保留** ——
    `report.py` / `portfolio.py` / `margin_account.py` / `position_view.py`
    四处都读它,改键名等于四处一起改,漏一处就静默拿到 None。

    ⚠ **`动作` 现在来自 `decision.build`,不再来自三维总分。**
    `总分` / `估值` / `基本面` / `确定性` 照旧算、照旧返回,但它们只进对照表。
    """
    import decision
    import guidance
    import outside_view
    import quarterly
    import sector_rules

    band, spot, our = v["前瞻PE带"], v["现价"], v["我们预测的未来四季净利"]
    rel = None
    if band.get("ok") and spot and our and our.get("mid"):
        pe = spot["close"] * v["总股本"] / our["mid"]
        rel = pe / band["p50"] if band["p50"] else None
    cp = f.get("产业链位置")
    edge_n = f.get("边界判定数") or 0
    sv, wv = score_valuation(rel)
    sc, wc = score_chain(cp, f.get("上游说明") or "")
    sf, wf = score_confidence(f["可用方法数"], f.get("方法一致", True), edge_n)
    total = sv + sc + sf
    old_act, old_horizon, old_why = decide(total)

    raw = Path(v.get("raw") or "data/raw")
    code = v["code"]
    sector = sector_rules.load(raw, code)
    lead = guidance.build(raw, code, sector["规则"]["领先指标"])
    qs = quarterly.build(raw, code, since="2022")["quarters"]
    outside = outside_view.build(raw, code, sector["规则"], qs)
    cash = quarterly.cash_and_orders({"quarters": qs})
    d = decision.build(v, f, position, sector, lead, outside, cash)

    return {"估值": (sv, wv), "基本面": (sc, wc), "确定性": (sf, wf),
            "总分": total, "rel": rel, "边界判定数": edge_n,
            "估值踩线": val_edge_note(rel),
            "方法一致": f.get("方法一致", True),
            "有融资负债": bool(position.get("margin_debt")),
            # ── 旧三维给出的动作,**只进对照表**,不是这份报告的结论 ──
            "旧动作": old_act, "旧期限": old_horizon, "旧档位理由": old_why,
            # ── 结论:动作只由 EV 定 ──────────────────────────────
            "动作": d["动作"],
            "期限": f"复核日 {d['复核日']}({d['复核日是什么报']})",
            "档位理由": (d.get("动作补充")
                         or (f"期望值 {d['EV']:+.1f}%,落在这一档"
                             if d.get("EV") is not None else d.get("why", ""))),
            "EV": d.get("EV"), "确信度分": (d.get("确信度") or {}).get("分"),
            "复核日": d["复核日"], "决策": d,
            "行业": sector.get("行业"), "行业数据": sector,
            "领先": lead, "基准率": outside,
            # 周期 / 设备行业上「估值」这一维本身失效 —— 对照表要标出来,
            # 否则读者会以为那个 −2 分是个有效的判断
            "估值维失效": (sector["规则"].get("估值尺") != "pe31")}


# ── 渲染:第 11 节 ────────────────────────────────────────────────────
def render(a: dict, v: dict, f: dict, position: dict, n: int, L: list) -> None:
    """第 11 节。主体是决策层的完整推导,后面接两段:

      · **具体怎么做** —— 建议对不对是一回事,这个账户能不能照做是另一回事
      · **对照:旧的三维打分说什么** —— 两边给出相反结论时,那本身是个信号
    """
    import decision_render
    decision_render.render(a["决策"], v, f, position, n, L)
    _how_to(a, v, f, position, L)
    _old_score(a, L)


def _how_to(a: dict, v: dict, f: dict, position: dict, L: list) -> None:
    """具体怎么做。**按动作分支,而且要看这个账户执行得了执行不了。**

    2026-09-02 踩过:中际旭创拿到「买入 / 加仓」,而账户可用保证金是 −171,089 ——
    加仓根本执行不了。建议本身没错,但对着一个不可能执行的动作写「分几笔买」是空话。
    """
    spot = v["现价"]
    px = spot["close"] if spot else None
    cost = position.get("cost")
    act = a["动作"]
    d = a["决策"]
    L.append("### 11.8 具体怎么做")
    L.append("")
    if not d.get("ok"):
        L.append("**没有动作就没有做法。** 先把上面说的那一块数据补上,再谈怎么做。")
        L.append("")
        return
    sc = d["三情景"]["情景"]
    if act.startswith("清仓"):
        L.append("- **分 2~3 笔卖完**,不要一次挂市价 —— 这几只日均成交额够,"
                 "但一次性大单会自己把价格砸下去")
        if cost and px:
            pl = (px / cost - 1) * 100
            L.append(f"- 你的成本 {cost:,.3f},现价 {px:,.2f},"
                     f"卖出会**实现 {pl:+.1f}% 的{'亏损' if pl < 0 else '盈利'}**。"
                     + ("浮亏变实亏心理上难,但**留着它的理由已经不成立了** —— "
                        "期望值是负的,继续拿是在赌一个我们没有依据支持的反弹。"
                        if pl < 0 else "这笔盈利可以变成账户的安全垫。"))
    elif act.startswith("减仓"):
        if d.get("超限"):
            o = d["超限"]
            L.append(f"- **至少减 {o['超出']:,.0f} 元**(现市值 {o['现市值']:,.0f},"
                     f"上限 {o['上限金额']:,.0f})。这个量不是拍的,是从 bear 情景"
                     f"({sc['bear']['涨跌']:+.1f}%)倒推的 —— 减到这里,"
                     f"bear 真的兑现时亏掉的净资产才在你设定的可承受线内。")
        else:
            import decision
            mvp = position.get("market_value")
            L.append(f"- **先减 {decision.TRIM_FRACTION:.0%}**"
                     + (f"(现市值 {mvp:,.0f} → 卖 "
                        f"{mvp * decision.TRIM_FRACTION:,.0f} 元)" if mvp else "")
                     + ",剩下的等下个季报再定 —— 我们的判断有明确的验证时点,"
                       "不用现在就赌到底。**账户文档第 7 节用的是同一个比例**"
                       "(`decision.TRIM_FRACTION`),两处不会分叉。")
        if position.get("margin_debt"):
            L.append(f"- **这只带 {position['margin_debt']:,.0f} 元融资负债**,"
                     f"减仓换来的现金优先还债,不要转去买别的 —— "
                     f"降杠杆的收益是确定的,换股的收益不是")
        L.append("- 不要等反弹再减。「等回本再走」是最贵的一句话:"
                 "它把卖出的条件从「判断变了」换成了「价格回到某个数」,"
                 "而价格不知道你的成本是多少")
    elif act.startswith("可加仓"):
        L.append(f"- **参考价位 {sc['bear']['价']:,.0f} 元(bear)~ "
                 f"{sc['base']['价']:,.0f} 元(base)**。"
                 f"现价 {px:,.2f} "
                 + ("在 base 之下,还有安全边际。" if px and px < sc["base"]["价"]
                    else "已经在 base 之上 —— 再买就是在赌 bull 兑现,"
                         "那时候该做的是等。"))
        if d["仓位上限"].get("ok"):
            pc = d["仓位上限"]
            L.append(f"- **加到 {pc['上限pct']:.1f}% of 净资产为止"
                     f"({pc['上限金额']:,.0f} 元)**"
                     + (f",你现在 {pc['现仓位pct']:.1f}%"
                        if pc.get("现仓位pct") is not None else "")
                     + " —— 上限不是仓位偏好,是从 bear 情景倒推出来的。")
        L.append(f"- **分 2~3 笔买,不要一次打满。** 判断有明确的验证时点"
                 f"({f['预测期']} 季报),分批等于把一次性的赌注拆成几次,"
                 f"中间还有机会按新数据改主意。")
    else:
        L.append("- **不加仓。** 期望值在 ±8% 那一档里,"
                 "也就是「按我们自己的概率算,这个位置买进去平均赚不到什么」。")
        L.append(f"- 想加的话,**等到 base 价位 {sc['base']['价']:,.0f} 元以下**"
                 f"(现价 {px:,.2f})—— 那时候同样的三个情景会算出一个更正的期望值。")
    # ⚠ **bear 价位要印在这一节里,不能只放决策日志。** 只看「具体怎么做」的读者
    #   拿不到那个数,而它是这份报告里唯一一个「跌到这里说明我们错了」的价格。
    #   决策日志那句是写给复核用的措辞,不是写给下单用的。
    L.append(f"- **bear 价位 {sc['bear']['价']:,.2f} 元"
             f"({sc['bear']['涨跌']:+.1f}%)可以当止损参考。** "
             f"它不是「跌到这里就该卖」的机械线,是**这套方法自己给的最悲观那一档**:"
             f"跌破它说明我们对这只票的判断已经被价格否掉了,"
             f"该做的是回到第 3 节重新看预测区间对不对,而不是继续等。"
             f"它同时也是第 11.5 节仓位上限的分母 —— "
             f"上限就是按「万一跌到这里,最多亏净资产的百分之几」倒推的。")
    L.append(f"- **下一个决策点是 {d['复核日']}**({d['复核日是什么报']}"
             f"的法定披露截止日)。届时拿实际值对第 3 节的区间、第 10 节的条件、"
             f"第 11.1 的三个价位,逐条核。")

    # ── 账户约束:能不能照做 ───────────────────────────────────────
    acct = position.get("账户") or {}
    margin = acct.get("可用保证金")
    if act.startswith("可加仓") and margin is not None and margin < 0:
        L.append("")
        L.append("**⚠ 但对你这个账户,这条建议的可执行版本是「不减」,不是「买」。**")
