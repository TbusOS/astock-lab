"""买卖建议 —— 动作由**期望值**定,三维打分降为对照。

## 2026-09-02 改了什么,为什么

原来动作由三个维度的总分决定(≥3 买入 · 1~2 持有 · 0 持有不加仓 · −1~−2 减仓)。
问题不在于分打得不对,在于**这个总分没法被验证**:
「估值 +1、基本面 +2、确定性 0,合计 +3」—— 三个季度之后回头看,
没有任何东西能说这个 +3 当时是对是错。于是每次重跑都只能重新拍一遍,
而且拍得看着都合理。

现在动作只由**期望值(EV)**决定,EV = 三个情景的价位按概率加权后的涨跌。
它能被季报证伪:实际涨跌回来一对,概率给高了给低了一目了然。
完整推导在 `decision.py`,报告第 11 节整张印出来。

**三维打分保留,但降为对照** —— 它回答的是另一个问题:
「相对自己历史贵不贵、份额在得还是在丢、推法有没有旁证」。
这三件事仍然值得单独看一眼,只是**不再直接决定动作**。
两边如果给出相反的结论,那本身是个信号:去看是哪一维和 EV 打架。

## 这份建议会错的地方(三维那部分)

· 三个维度**都不含估值以外的价格信息** —— 不看 K 线、不看资金流
· 基本面这一维只看**相对上游的份额变化**,不看毛利率、不看新产品
· 分数是离散的,1.79x 和 1.81x 会掉进不同档。**边界附近别当真**

## 三个维度分别是什么

    ① 估值   = 现价 3+1 PE ÷ 这只票**自己**历史 3+1 PE 的 p50
       用比值不用绝对 PE —— 油服和光模块的合理倍数不在一个量级。
       ⚠ **周期 / 设备行业上这一维本身就不该看**(PE 在盈利低谷给「便宜」
       的假信号),所以那些票的对照表会标出来「这一维在本行业失效」。
    ② 基本面 = 相对上游开支的增速倍数(水平 + 趋势)
    ③ 确定性 = 三个预测方法里有几个通过自检,**再看它们同不同意**
"""
