WIDTH_MIN_PCT = 5.0          # 区间宽度低于这个数,当场说「这条预测几乎注定错」


def _narrow_hit(bt: dict):
    """回测里「宽度 <10% 的区间」命中率。拿不到就返回 None,由调用方决定怎么说。"""
    for r in (bt.get("按宽度") or []):
        if r.get("档") == "<10%":
            return r.get("命中率"), r.get("n")
    return None, None


def _render_width_note(f: dict, bt: dict, L: list) -> None:
    """A3:区间太窄时当场泼冷水。

    **为什么要有这一段**:窄区间看起来像「我们很有把握」,回测说的正相反 ——
    宽度 <10% 的 17 个季度只命中 1 个。窄只说明三条方法给的线段碰巧挨得近,
    不说明它们离真值近。不写这一句,读者只会看到一个精确的区间。

    它在不适用时会怎样:区间宽(>5%)时这一段整个不出现,不会误伤;
    回测文件不在时只说宽度、不引用命中率,不编一个数出来。
    """
    w = f.get("区间宽度pct")
    if w is None or w >= WIDTH_MIN_PCT:
        return
    rate, n = _narrow_hit(bt)
    L.append("")
    L.append(f"> ⚠ **区间宽度只有 {w:.1f}%**"
             + (f",而回测里 <10% 宽度的区间命中率只有 {rate:.0f}%"
                f"({n} 个季度)—— **这条预测几乎注定错**。"
                if rate is not None else
                " —— 这么窄的区间几乎注定被实际值穿出去(还没跑回测,"
                "跑 `tools/backtest.py --walkforward` 之后这里会有历史命中率)。")
             + "窄不是把握大,是三条方法给的线段碰巧挨得近。")


def _render_only_yoy(f: dict, bt: dict, L: list) -> None:
    """A5:只剩同比法时,把它在回测里的成绩摆出来。

    同比法是三个里最差的:它通过自检的次数最多(50 次里 38 次),
    中枢误差却是另外两个的两三倍。「唯一能用的方法」听起来像「至少还有一个」,
    实际是「只剩最不准的那个」——这两句话给读者的印象完全相反。

    它在不适用时会怎样:可用方法不止一个、或可用的那个不是同比法时,
    这一段不出现;回测文件不在时只说「它是三个里最差的」,不给数字。
    """
    ok = [m["name"] for m in f["methods"] if m.get("ok")]
    if ok != ["同比法"]:
        return
    y = (bt.get("方法") or {}).get("同比法") or {}
    L.append("")
    L.append("> ⚠ **唯一能用的是同比法,而它是三个方法里最差的那个。**"
             + (f"走前回测里它的中枢误差中位 {y['中位绝对偏差']:.1f}%、"
                f"命中率 {y['命中率']:.0f}%(通过自检 {y['n']} 次),"
                f"另外两个是 {(bt['方法'].get('环比法') or {}).get('中位绝对偏差', 0):.1f}% "
                f"和 {(bt['方法'].get('存货法') or {}).get('中位绝对偏差', 0):.1f}%。"
                if y.get("中位绝对偏差") is not None else
                "(还没跑回测,跑 `tools/backtest.py --walkforward` 之后这里会有具体误差。)")
             + "所以确信度里「方法互相印证」那一条判 **0 分** —— "
               "不是因为「只有一个」,是因为**剩下的这一个本身就不准**。")


def render_backtest(f: dict, L: list) -> None:
    """A4:这个方法组合在过去 46 个季度的表现。**数字全部从 json 读,不写死。**

    为什么单独一段:上面每一节讲的都是「这一季我们怎么推的」,
    读者没有任何东西可以判断「这么推过去准不准」。
    没有这一段,区间的宽窄就只能靠感觉。

    它在不适用时会怎样:`data/backtest/revenue-summary.json` 不在时写「未回测」,
    **不拿任何默认值顶替** —— 顶替出来的百分比看着像证据。
    """
    bt = f.get("回测")
    L.append("")
    L.append("**这个方法组合在过去这些季度里表现如何**")
    L.append("")
    if not bt:
        L.append("**未回测。** `data/backtest/revenue-summary.json` 不在盘上,"
                 "所以这一段没有数字可给。生成:"
                 "`$VENV/bin/python tools/backtest.py --walkforward --raw data/raw`。")
        L.append("")
        L.append("> 不给一个默认值顶替 —— 顶替出来的百分比看着像证据,"
                 "而它其实只是一个占位。")
        L.append("")
        return
    u, s = bt["并集"], bt.get("样本") or {}
    L.append(f"做法:把时间倒回去,**只用截至目标季前一季的数据**跑同样这三个方法,"
             f"再和后来真实发生的比。样本 {s.get('票数', '?')} 只票 × "
             f"{s.get('季度', '?')} 共 {s.get('样本数', '?')} 个「票 × 季度」,"
             f"其中 {u['n']} 个能给出区间。")
    L.append("")
    L.append("| 量 | 值 | 怎么读 |")
    L.append("|---|---:|---|")
    L.append(f"| 并集命中率 | **{u['命中率']:.0f}%** "
             f"| {u['命中']}/{u['n']} 个季度的实际值落在区间里 |")
    L.append(f"| 中枢误差(中位) | **{u['中位绝对偏差']:.1f}%** "
             f"| 和命中率无关 —— 它量的是「中枢偏了多少」,不受区间宽窄影响 |")
    L.append(f"| 平均偏差 | **{u['平均偏差']:+.1f}%** "
             f"| 正数 = **系统性偏低**(真实值高于中枢)。三条方法都是外推,"
             f"上行期一起慢半拍 |")
    L.append(f"| 区间中位宽度 | {u['中位宽度']:.0f}% | 并集的代价:宽 |")
    L.append("")
    tp = bt.get("拐点") or {}
    if tp.get("样本"):
        L.append(f"**偏低偏在最要命的地方**:{len(tp['样本'])} 次大幅低估"
                 f"(实际比中枢高 50% 以上)**全部发生在同比增速跳升的那一季** —— "
                 + "、".join(f"{x['name']} {x['target']}(+{x['偏差']:.0f}%)"
                             for x in tp["样本"]) + "。"
                 f"三个方法都是外推历史,加速时会一起慢半拍,"
                 f"**它们的「互相印证」在拐点上是同时错的印证**。")
        L.append("")
    L.append("| 单个方法 | 通过自检 | 命中率 | 中枢误差(中位) |")
    L.append("|---|---:|---:|---:|")
    for name in ("存货法", "同比法", "环比法"):
        m = (bt.get("方法") or {}).get(name)
        if not m:
            continue
        L.append(f"| {name} | {m['n']}/{s.get('样本数', '?')} | {m['命中率']:.0f}% "
                 f"| {m['中位绝对偏差']:.1f}% |")
    L.append("")
    L.append("| 区间宽度 | 季度数 | 命中率 |")
    L.append("|---|---:|---:|")
    for r in (bt.get("按宽度") or []):
        L.append(f"| {r['档']} | {r['n']} | {r['命中率']:.0f}% |")
    L.append("")
    if bt.get("按宽度用的样本"):
        L.append(f"(宽度这一张用的是{bt['按宽度用的样本']}。)")
        L.append("")
    ob = bt.get("旧生产取法(先交集空了退并集)")
    if ob:
        L.append(f"**这就是「取交集」被否决的那组数**:旧做法(先取交集、交集为空才退并集)"
                 f"在同样这 {ob['n']} 个季度里命中 {ob['命中']} 个"
                 f"({ob['命中率']:.0f}%),中位宽度只有 {ob['中位宽度']:.0f}%;"
                 f"一律取并集命中 {u['命中']} 个({u['命中率']:.0f}%)。"
                 f"**两者的中枢误差完全一样**({ob['中位绝对偏差']:.1f}% vs "
                 f"{u['中位绝对偏差']:.1f}%)—— 交集没有让中枢更准,只是让区间更窄。")
        L.append("")
    L.append("> **命中率完全被宽度牵着走** —— 所以判断一个方法好不好要三个量一起看:"
             "命中率、中枢误差(和宽度无关)、区间宽度。只看命中率会得出"
             "「区间开得越宽方法越好」这种反的结论。")
    L.append("")
    L.append(f"来源:`data/backtest/revenue-summary.json`(跑于 {bt.get('生成于', '?')},"
             f"窗口 {bt.get('窗口', '?')})。重跑:"
             f"`$VENV/bin/python tools/backtest.py --walkforward --raw data/raw`。")
    L.append("")


def render(f: dict) -> str:
    def y(v, nd=1):
        return "—" if v is None else f"{v / 1e8:,.{nd}f}"

    L = [f"### {f['code']} · 我们自己对 {f['预测期']} 的预测", ""]
    L.append(f"最新已披露:**{f['最新已披露']}**。以下全部由公司自己报表里的数推出,"
             f"**没有引用任何机构的预测**。")
    L.append("")
    L.append("**先说清楚是哪三个方法。** 三者共用的只有营收这一个观测量,"
             "**出错的原因互不相同** —— 存货法看供给侧已经花出去的钱,"
             "同比法看需求侧的增长趋势,环比法看这门生意本身的季节形状。"
             "能用的方法**取并集**:区间罩住每一个方法给的范围,"
             "读作「至少一个方法这么认为」。"
             "⚠ 这个独立性**只在平稳期成立** —— 三条都是外推,"
             "增速拐头那一季会一起慢半拍,而且是同方向错。")
    L.append("")
    for name, doc in METHOD_DOC.items():
        m = next((x for x in f["methods"] if x["name"] == name), None)
        mark = "✓ 本次适用" if (m and m.get("ok")) else "✗ 本次不适用"
        L.append(f"**{name}**　{mark}")
        L.append("")
        L.append(f"- **是什么**:{doc['一句话']}")
        L.append(f"- **为什么这么算**:{doc['为什么成立']}")
        L.append(f"- **算式**:`{doc['算式']}`")
        L.append(f"- **什么时候不能用**:{doc['什么时候不能用']}")
        if m:
            L.append(f"- **这只票的实际情况**:"
                     + (m.get("依据", "") if m.get("ok") else m.get("why", "")))
        L.append("")
    L.append("三个方法在这只票上的结果:")
    L.append("")
    L.append("| 方法 | 能不能用 | 结果 | 依据 / 不能用的原因 |")
    L.append("|---|---|---:|---|")
    for m in f["methods"]:
        if m.get("ok"):
            L.append(f"| {m['name']} | ✓ | {y(m['low'])} ~ {y(m['high'])} 亿 "
                     f"| {m['依据']} |")
        else:
            L.append(f"| {m['name']} | ✗ | — | {m['why']} |")
    L.append("")

    n = f["可用方法数"]
    if not n:
        L.append("> **三个方法一个都不适用。** 这只票的下季营收我们没有可靠的推法 —— "
                 "如实写出来,而不是硬给一个数。要补的是更细的数据"
                 "(分产品/分客户收入、订单、产能),现有财报颗粒不够。")
        return "\n".join(L)

    edge_n = f.get("边界判定数") or 0
    if edge_n:
        L.append(f"> ⚠ **上面有 {edge_n} 个判定踩在阈值边上**(离阈值不到它的 10%)。"
                 f"阈值两边是两个相反的结论,而差距只有几个点 —— "
                 f"下个季度重跑时它很可能翻面。翻面时该问的是"
                 f"「公司变了没有」,多半答案是没变,只是噪声过了线。")
        L.append("")

    b = f["营收区间"]
    L.append(f"**{f['预测期']} 单季营收:{y(b['low'])} ~ {y(b['high'])} 亿"
             f"(中枢 {y(b['mid'])} 亿)**,{n} 个方法取{f['区间取法']}。")
    bt = f.get("回测") or {}
    if n >= 2 and not f.get("方法一致", True):
        L.append("")
        L.append(f"> ⚠ **{n} 个方法都通过了自检,但它们给的区间不重叠。**"
                 f"几个方法给的范围不重叠,说明这只票当期的形状不稳定,"
                 f"区间因此更宽;"
                 + (f"历史上这种情况命中率反而最高"
                    f"({bt['矛盾退并集']['命中']}/{bt['矛盾退并集']['n']} = "
                    f"{bt['矛盾退并集']['命中率']:.0f}%,是所有情形里最高的),"
                    if bt.get("矛盾退并集", {}).get("n") else
                    "历史上这种情况命中率反而最高,")
                 + "代价是信息量少 —— 一个 61~114 亿这么宽的区间,"
                   "拿它做决策能得到的东西确实有限。")
    if n == 1:
        L.append("")
        L.append("> ⚠ **只有 1 个方法适用**,没有第二个来交叉验证。"
                 "这个区间的可信度比有 2~3 个方法时低一档,用的时候要打折。")
    _render_width_note(f, bt, L)
    _render_only_yoy(f, bt, L)
    L.append("")

    mg = f["利润率"]
    if mg["毛利率"]:
        g = mg["毛利率"]
        L.append(f"- **毛利率**:近四季 {g['低']:.1f}%~{g['高']:.1f}%,中位 {g['中位']:.1f}%")
    if mg["三费率"]:
        e = mg["三费率"]
        L.append(f"- **三费率**:近四季 {e['低']:.1f}%~{e['高']:.1f}%")
    if mg["财务费用波动"] is not None:
        fin = mg["财务费用"]
        L.append(f"- **财务费用**:近四季 {y(fin['低'], 2)} ~ {y(fin['高'], 2)} 亿,"
                 f"波动 {y(mg['财务费用波动'], 2)} 亿。**这一项主要是汇兑,和生意好坏无关**,"
                 f"但能吃掉几个点的净利率 —— 它是净利预测里最大的不确定来源。")
    p = f["归母净利区间"]
    if p:
        L.append("")
        L.append(f"**{f['预测期']} 单季归母净利:{y(p['low'])} ~ {y(p['high'])} 亿"
                 f"(中枢 {y(p['mid'])} 亿)**,= 营收区间 × 近四季净利率区间。")
    render_backtest(f, L)
    cp = f.get("产业链位置")
    if cp:
        up = cp["上游"]
        L.append("")
        L.append(f"**在产业链里的位置:{cp['判断']}**"
                 f"(相对{up}的增速倍数,{cp['期间']} 从 "
                 f"{cp['起点']:.2f}x 变到 {cp['终点']:.2f}x)")
        if not cp.get("可打分", True):
            L.append("")
            L.append(f"> ⚠ **这四个可比点不连续,所以这一节只展示,不参与打分。**"
                     f"它们是 {'/'.join(cp['四点'])},横跨 {cp['跨越季度数']} 个季度"
                     f"(连续的话应该是 4 个)。中间被跳掉的季度里发生过什么完全看不见,"
                     f"首尾一比却会得出一个像模像样的趋势。"
                     f"跳掉的原因有两种:上游同比低于 10%(除以接近 0 的数会让倍数爆掉),"
                     f"或公司营收同比 ≤0(倍数是负数,没有含义)。"
                     f"本轮共跳过 {cp['跳过']} 个季度。")
        L.append("")
        L.append(f"| 季度 | {up}同比 | 公司营收同比 | 倍数 |")
        L.append("|---|---:|---:|---:|")
        for x in cp["points"][-6:]:
            L.append(f"| {x['period']} | {x['上游同比']:.1f}% "
                     f"| {x['公司营收同比']:.1f}% | {x['倍数']:.2f}x |")
        L.append("")
        import forecast
        kind = (forecast.UPSTREAM.get(
            forecast.UPSTREAM_OF.get(f["code"], ""), {}) or {}).get("kind")
        src = ("上游数据来自各家 10-Q/10-K 的申报原值(SEC XBRL)。" if kind == "sec" else
               "上游数据来自各家自己的现金流量表(「购建固定资产、无形资产和其他"
               "长期资产所支付的现金」),和公司营收出自同一套报表。")
