"""第 11 节的完整推导渲染 —— 三情景 / 概率四步 / 期望值 / 确信度 / 仓位上限。

从 `decision.py` 拆出来的理由:那边**算**,这边**写**。
`decision.py` 原来已经贴着单文件行数上限 —— 而这一批要往里加
净资产增长路径、清仓的盈利侧门槛、硬上限、期望值分解。算和写混在一个文件里,
改一句措辞会碰到算概率的代码。

**这里不做任何判断**,只把 `decision.build()` 已经算好的东西变成话。
每一句都按当轮数据分支 —— 写死的句子在数据变了之后照样合理地印着,而且不报错。

依赖:无(读 decision.build 的输出)。
"""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

